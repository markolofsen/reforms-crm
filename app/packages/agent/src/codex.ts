import path from "node:path";
import type { HubPaths } from "@hub/config/paths";
import { CODEX_FORBIDDEN_PREFIXES, deniedToolsOf, HUB_MCP_SERVERS, otherProjects } from "./deny";
import { CODEX_BYPASS, codexModeArgs, protectedPaths } from "./session";

// A Codex session of `hub agent --cli codex` (P49 S9, S10), built without writing. Codex has no strict-MCP flag and its
// `-c` overrides merge into the owner's tables, so a hub session gets its own `CODEX_HOME` (research 21 section 6):
// `<state>/codex/<slug>/` with `config.toml` (the hub's MCP servers only, the send tools off, the sandbox profile),
// `rules/hub.rules` (forbidden prefixes), `skills/` (links to the core skills) and `auth.json` (a link to the owner's).

/** `<state>/codex/<slug or _unbound>`: the `CODEX_HOME` of one project's sessions. */
export const codexHome = (paths: HubPaths, slug: string | undefined): string => path.join(paths.codexHomes, slug ?? "_unbound");

/** The name of the generated permissions profile. */
export const CODEX_PROFILE = "hub";

const str = (v: string): string => JSON.stringify(v); // a JSON string is a valid TOML basic string
const arr = (v: readonly string[]): string => `[${v.map(str).join(", ")}]`;
const inline = (o: Record<string, string>): string => `{ ${Object.entries(o).map(([k, v]) => `${str(k)} = ${str(v)}`).join(", ")} }`;

export interface CodexSessionInput {
  paths: HubPaths;
  projectsDir: string;
  slug: string | undefined;
  unattended: boolean;
  /** The instance's MCP servers (`.mcp.json` shape, already made absolute for the instance), by name. */
  servers: Record<string, Record<string, unknown>>;
  /** The binding prompt (one project per session). */
  instructions: string;
  /** `model` and `model_reasoning_effort` carried over from the owner's own config, when set there. */
  carry?: Record<string, string>;
}

/**
 * `config.toml`. The sandbox is a permissions profile in both modes: workspace-write (`:workspace_roots` writable,
 * the disk readable) with the protected paths read-only and secrets and other projects unreadable, network off. A
 * plain `--sandbox workspace-write` cannot keep `state/projects` (the send policy) read-only, so the profile replaces it.
 */
export function codexConfigToml(i: CodexSessionInput): string {
  const out: string[] = ["# Generated by `hub agent --cli codex` for every session (P49 S10). Edits are overwritten.", ""];
  for (const [k, v] of Object.entries(i.carry ?? {})) out.push(`${k} = ${str(v)}`);
  out.push(`approval_policy = ${str(i.unattended ? "never" : "on-request")}`, `default_permissions = ${str(CODEX_PROFILE)}`, `developer_instructions = ${str(i.instructions)}`, "");
  out.push(`[permissions.${CODEX_PROFILE}.filesystem]`, `":root" = "read"`, `":workspace_roots" = "write"`);
  // One entry per path (TOML refuses a key twice): unreadable wins over read-only.
  const access = new Map<string, "read" | "none">(protectedPaths(i.paths).map((p) => [p, "read"]));
  for (const p of [i.paths.secrets, ...otherProjects(i.projectsDir, i.slug).map((o) => path.join(i.projectsDir, o))]) access.set(p, "none");
  for (const [p, a] of access) out.push(`${str(p)} = ${str(a)}`);
  out.push("", `[permissions.${CODEX_PROFILE}.network]`, "enabled = false", "");
  out.push(`[projects.${str(i.paths.home)}]`, `trust_level = "trusted"`, "");
  for (const name of HUB_MCP_SERVERS) {
    const s = i.servers[name];
    if (!s) continue;
    out.push(`[mcp_servers.${str(name)}]`);
    if (s.type === "stdio") {
      out.push(`command = ${str(String(s.command))}`);
      if (Array.isArray(s.args)) out.push(`args = ${arr(s.args.map(String))}`);
      if (s.env && typeof s.env === "object") out.push(`env = ${inline(Object.fromEntries(Object.entries(s.env as Record<string, unknown>).map(([k, v]) => [k, String(v)])))}`);
    } else out.push(`url = ${str(String(s.url))}`);
    const off = deniedToolsOf(name);
    if (off.length) out.push(`disabled_tools = ${arr(off)}`);
    out.push("");
  }
  return out.join("\n");
}

/** `rules/hub.rules`: the hub's doors as forbidden command prefixes (Starlark). A belt beside the sandbox. */
export function codexRules(): string {
  return [
    "# Generated by `hub agent --cli codex` (P49 S10). Forbidden: refused without a prompt, in every mode.",
    ...CODEX_FORBIDDEN_PREFIXES.map((p) => `prefix_rule(pattern = ${arr(p)}, decision = "forbidden", justification = "the hub's send pipeline is a person's: drafts only")`),
    "",
  ].join("\n");
}

/** The Codex flags: the instance root as the workspace, the mode's approval. Never the bypass flag. */
export function codexArgs(i: { paths: HubPaths; unattended: boolean; extra?: string[] }): string[] {
  const args = ["-C", i.paths.home, ...codexModeArgs(i.unattended), ...(i.extra ?? [])];
  if (args.includes(CODEX_BYPASS) || args.includes("--yolo")) throw new Error(`hub agent never runs Codex with ${CODEX_BYPASS}: it turns the sandbox off`);
  return args;
}

/** True when a Codex config text turns the sandbox off (the Agent tools check fails on it). */
export const codexConfigBypasses = (toml: string): boolean => /^\s*sandbox_mode\s*=\s*"danger-full-access"/m.test(toml) || /dangerously-bypass/.test(toml);
