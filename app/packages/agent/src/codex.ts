import os from "node:os";
import path from "node:path";
import { codexSessionPaths, type HubPaths } from "@hub/config/paths";
import { CODEX_FORBIDDEN_PREFIXES, deniedToolsOf, HUB_MCP_SERVERS, otherDrops, otherProjects } from "./deny";
import { focusHookCommand, logHookCommand } from "./claude";
import { CODEX_BYPASS, CODEX_MODE_ARGS, OWNER_SECRET_FILES, protectedPaths } from "./session";
import { HUB_MCP_WRITE_TOOLS } from "./mcp/server";
import { NOTION_ALLOWED } from "@hub/projects/notion-tools";

// A Codex session of `hub agent --cli codex` (P49 S9, S10), built without writing. Codex has no strict-MCP flag and its
// `-c` overrides merge into the owner's tables, so a hub session gets its own `CODEX_HOME` (research 21 section 6):
// `<state>/codex/<slug>/` with `config.toml` (the hub's MCP servers only, the send tools off, the sandbox profile),
// `rules/hub.rules` (forbidden prefixes), `skills/` (links to the core skills) and `auth.json` (a link to the owner's).

/** `<state>/codex/<slug or _unbound>`: the `CODEX_HOME` of one project's sessions. */
export const codexHome = (paths: HubPaths, slug: string | undefined): string => codexSessionPaths(paths, slug).home;

/** Codex events `hub log --hook` takes (P54). */
export const CODEX_LOG_EVENTS = ["SessionStart", "Stop", "PermissionRequest"] as const;

/** The name of the generated permissions profile. */
export const CODEX_PROFILE = "hub";

/** How long Codex lets one `hub` tool call run (P65 S5): above the writer's own budgets (45 s wait, 150 s osascript cut). */
export const HUB_TOOL_TIMEOUT_SEC = 300;

const str = (v: string): string => JSON.stringify(v); // a JSON string is a valid TOML basic string
const arr = (v: readonly string[]): string => `[${v.map(str).join(", ")}]`;
const inline = (o: Record<string, string>): string => `{ ${Object.entries(o).map(([k, v]) => `${str(k)} = ${str(v)}`).join(", ")} }`;

export interface CodexSessionInput {
  paths: HubPaths;
  projectsDir: string;
  slug: string | undefined;
  /** The instance's MCP servers (`.mcp.json` shape, already made absolute for the instance), by name. */
  servers: Record<string, Record<string, unknown>>;
  /** The binding prompt (one project per session). */
  instructions: string;
  /** `model` and `model_reasoning_effort` carried over from the owner's own config, when set there. */
  carry?: Record<string, string>;
  /** The Node that runs the hub (the focus hook calls `hub focus --hook` with it). */
  nodeBin?: string;
  /** The owner's home (his token files and `~/.ssh`); the OS user's by default. */
  userHome?: string;
}

/**
 * P159 (owner 2026-11-26: ssh always works): the owner's token files Codex may not read now that its network is on
 * ({@link OWNER_SECRET_FILES} but `~/.ssh`), and `~/.ssh` writable. Measured on Codex 0.153: a prefix rule `allow` does not take
 * a command out of the sandbox under `approval_policy = "never"` (the model is told never to ask for escalation), and the
 * proxy mode (per-host rules) carries HTTP only, so ssh needs the direct network. Inside the sandbox ssh reads its own key (a
 * key denied leaves only the ssh-agent, empty after a reboot: `Permission denied (publickey)`) and binds its ControlMaster
 * socket under `~/.ssh` (a read-only `~/.ssh` is a fatal `unix_listener: cannot bind`). Codex accepts only `deny` on a glob,
 * so the folder is writable as a whole. The trade-off, written down: a Codex command can read the private key and reach
 * loopback (the Hub's API and mail-mcp's port).
 */
export function codexOwnerAccess(userHome: string = os.homedir()): Array<[string, "write" | "none"]> {
  return OWNER_SECRET_FILES.map((f): [string, "write" | "none"] => [path.join(userHome, f), f === ".ssh" ? "write" : "none"]);
}

/**
 * `config.toml` of an owner's session. The sandbox is a permissions profile: workspace-write (`:workspace_roots` writable,
 * the disk readable) with the protected paths read-only and secrets and other projects unreadable, the network on (P159, for
 * ssh) and the owner's token files unreadable ({@link codexOwnerAccess}). A
 * plain `--sandbox workspace-write` cannot keep `state/projects` (the send policy) read-only, so the profile replaces it.
 */
export function codexConfigToml(i: CodexSessionInput): string {
  const out: string[] = ["# Generated by `hub agent --cli codex` for every session (P49 S10). Edits are overwritten.", ""];
  for (const [k, v] of Object.entries(i.carry ?? {})) out.push(`${k} = ${str(v)}`);
  out.push(`approval_policy = "never"`, `default_permissions = ${str(CODEX_PROFILE)}`, `developer_instructions = ${str(i.instructions)}`, "");
  out.push(`[permissions.${CODEX_PROFILE}.filesystem]`, `":root" = "read"`, `":workspace_roots" = "write"`);
  // One entry per path (TOML refuses a key twice): unreadable wins over read-only.
  const access = new Map<string, "read" | "write" | "none">([...codexOwnerAccess(i.userHome), ...protectedPaths(i.paths).map((p): [string, "read"] => [p, "read"])]);
  // P112 S3: another project's session files (its project capability) and Codex home are closed. Its folder and the other
  // tabs' drops are read-only (P140 K3: an owner's session reads any project's files).
  const others = otherProjects(i.projectsDir, i.slug);
  const open = "read";
  const closed: Array<[string, "read" | "none"]> = [[i.paths.secrets, "none"], ...others.flatMap((o): Array<[string, "read" | "none"]> => [[path.join(i.projectsDir, o), open], [path.join(i.paths.stateProjects, o), "none"], [path.join(i.paths.codexHomes, o), "none"]]), ...otherDrops(i.paths, i.projectsDir, i.slug).map((d): [string, "read" | "none"] => [d, open])];
  for (const [p, a] of closed) access.set(p, a);
  for (const [p, a] of access) out.push(`${str(p)} = ${str(a)}`);
  out.push("", `[permissions.${CODEX_PROFILE}.network]`, "enabled = true", "");
  out.push(`[projects.${str(i.paths.home)}]`, `trust_level = "trusted"`, "");
  // P51: the focus line per prompt (Codex 0.146 `UserPromptSubmit`, measured in F0). Codex runs only trusted hooks; this one is
  // the hub's own, in a home only the hub writes, so the launcher passes `--dangerously-bypass-hook-trust` (see `codexArgs`).
  const node = i.nodeBin ?? process.execPath;
  out.push("[[hooks.UserPromptSubmit]]", "[[hooks.UserPromptSubmit.hooks]]", `type = "command"`, `command = ${str(focusHookCommand(node, i.paths, "codex"))}`, "timeout = 5", "");
  // P54: the session log. Codex 0.146 skips async hooks, so these block: Stop runs once per turn and imports that turn's
  // tool calls from the rollout (no hook per tool call); SessionEnd is left out (its 1 s budget is below a Node start).
  for (const e of CODEX_LOG_EVENTS) out.push(`[[hooks.${e}]]`, `[[hooks.${e}.hooks]]`, `type = "command"`, `command = ${str(logHookCommand(node, i.paths, "codex"))}`, "timeout = 10", "");
  for (const name of HUB_MCP_SERVERS) {
    const s = i.servers[name];
    if (!s) continue;
    out.push(`[mcp_servers.${str(name)}]`);
    if (s.type === "stdio") {
      out.push(`command = ${str(String(s.command))}`);
      if (Array.isArray(s.args)) out.push(`args = ${arr(s.args.map(String))}`);
      if (s.env && typeof s.env === "object") out.push(`env = ${inline(Object.fromEntries(Object.entries(s.env as Record<string, unknown>).map(([k, v]) => [k, String(v)])))}`);
    } else out.push(`url = ${str(String(s.url))}`);
    // Decision 0046: an owner's session keeps `hub.messenger_send` (a background run has no Codex session at all).
    const off = deniedToolsOf(name, "owner");
    // P112 S3: Notion is default-deny; Codex has no guard hook to refuse an unknown tool, so its allow-list is the server's own.
    if (name === "notion") out.push(`enabled_tools = ${arr([...NOTION_ALLOWED])}`);
    if (off.length) out.push(`disabled_tools = ${arr(off)}`);
    // P65 S5: `draft_write` waits up to 45 s for a slow Mail, then reads and replaces (one call took 53 s on 2026-11-19).
    // Codex cuts a tool call at 60 s by default; cut, the agent would see a generic error and write again (a second draft).
    if (name === "hub") out.push(`tool_timeout_sec = ${HUB_TOOL_TIMEOUT_SEC}`);
    // `approval_policy = "never"` rejects MCP tools that still require approval: the hub's own writing tools (drafts, records,
    // the pointer, the one send on the owner's word, each checked again by the server) get an approval override by name, and
    // no other server's tool does.
    if (name === "hub") for (const t of HUB_MCP_WRITE_TOOLS) out.push(`[mcp_servers."hub".tools.${str(t)}]`, `approval_mode = "approve"`);
    out.push("");
  }
  return out.join("\n");
}

/** `rules/hub.rules`: the hub's doors as forbidden command prefixes (Starlark). A belt beside the sandbox. */
export function codexRules(): string {
  return [
    "# Generated by `hub agent --cli codex` (P49 S10). Forbidden: refused without a prompt, in every mode.",
    ...CODEX_FORBIDDEN_PREFIXES.map((p) => `prefix_rule(pattern = ${arr(p)}, decision = "forbidden", justification = "the hub's send pipeline is a person's: drafts only")`),
    "",
  ].join("\n");
}

/**
 * Codex runs a hook only after the person trusted it; the hub's focus hook is generated into a home only the hub writes (a
 * protected path of the sandbox, like `<home>/.codex`), so the launcher vouches for it. This flag skips hook trust only; the
 * sandbox and approvals are untouched (not {@link CODEX_BYPASS}).
 */
export const CODEX_HOOK_TRUST = "--dangerously-bypass-hook-trust";

/** The Codex flags: the instance root as the workspace, the mode's approval, the hub's own hook trusted. Never the sandbox bypass flag. */
export function codexArgs(i: { paths: HubPaths; extra?: string[] }): string[] {
  const args = ["-C", i.paths.home, ...CODEX_MODE_ARGS, CODEX_HOOK_TRUST, ...(i.extra ?? [])];
  if (args.includes(CODEX_BYPASS) || args.includes("--yolo")) throw new Error(`hub agent never runs Codex with ${CODEX_BYPASS}: it turns the sandbox off`);
  return args;
}

/** True when a Codex config text turns the sandbox off (the Agent tools check fails on it). */
export const codexConfigBypasses = (toml: string): boolean => /^\s*sandbox_mode\s*=\s*"danger-full-access"/m.test(toml) || /dangerously-bypass/.test(toml);
