// A project's own development kanban: `<instance>/projects/<slug>/@dev/` (plan P41). The directory is the status; the track table in
// the folder's README.md is generated here, from the directories and each plan's header. The Hub's own kanban uses the same code
// (`hub dev index --path <@dev folder>`), so there is one generator and one set of drift checks.
import { existsSync, mkdirSync, readdirSync, readFileSync, statSync, writeFileSync } from "node:fs";
import { dirname, join, relative } from "node:path";
import { CORE_ROOT } from "@hub/config/paths";

export const DEV_DIR = "@dev";
/** The skeleton a new project starts with (plain files in the core; `{{SLUG}}` is filled in). */
export const DEV_TEMPLATE = `app/projects/_template/${DEV_DIR}`; // a path inside the core checkout, not the instance projects folder

const BEGIN = "<!-- tracks:begin (generated by `hub dev index`, do not edit) -->";
const END = "<!-- tracks:end -->";
/** Directory -> the status word a plan in it may start with. Order = order of the table. */
const STATES: [string, string][] = [["active", "ACTIVE"], ["blocked", "BLOCKED"], ["planned", "PLANNED"], ["completed", "DONE"], ["_archive", "PARKED"]];
const NEXT_MAX = 200;

const natural = (a: string, b: string) => a.localeCompare(b, "en", { numeric: true });
const cell = (s: string) => s.replace(/\|/g, "\\|").replace(/\s+/g, " ").trim();
const clip = (s: string) => (s.length > NEXT_MAX ? `${s.slice(0, NEXT_MAX - 1).trimEnd()}…` : s);

/** A header line (`Owner:`, `Next action:`) of a plan; falls back to the same key written inline on the `Status:` line. */
function header(text: string, key: string): string {
  const own = new RegExp(`^${key}:[ \\t]*(.*)$`, "m").exec(text);
  if (own) return own[1] ?? "";
  const status = /^Status:.*$/m.exec(text);
  const inline = status && new RegExp(`${key}:[ \\t]*(.*)$`).exec(status[0]);
  return inline ? (inline[1] ?? "") : "";
}

export interface Kanban {
  /** Number of tracks found. */
  tracks: number;
  /** A plan missing, a plan Status word that contradicts its directory, or a README that is missing or stale. */
  problems: string[];
  /** The README text the directories call for; equal to the file's text when nothing is stale. */
  readme: string;
  /** README.md is stale (differs from `readme`). */
  stale: boolean;
}

/** Reads one `@dev` folder. Pure: writes nothing. Throws when README.md has no track markers (nothing to generate into). */
export function readKanban(dev: string): Kanban {
  const problems: string[] = [];
  const rows: string[] = [];
  for (const [dir, state] of STATES) {
    const base = join(dev, dir);
    if (!existsSync(base)) continue;
    const names = readdirSync(base, { withFileTypes: true }).filter((d) => d.isDirectory()).map((d) => d.name).sort(natural);
    for (const name of names) {
      const plan = join(base, name, "PLAN.md");
      if (!existsSync(plan)) { problems.push(`${dir}/${name}: no PLAN.md`); continue; }
      const text = readFileSync(plan, "utf8");
      const word = /^Status:[ \t]*([A-Za-z]+)/m.exec(text)?.[1];
      const claimed = STATES.find(([, s]) => s === (word ?? "").toUpperCase());
      if (claimed && claimed[1] !== state) problems.push(`${dir}/${name}: plan Status says ${claimed[1]}, directory says ${state}`);
      const owner = header(text, "Owner").split(/[;(.]/)[0] || "-";
      const next = header(text, "Next action") || "-";
      rows.push(`| [${name}](${dir}/${name}/PLAN.md) | ${state} | ${cell(owner)} | ${cell(clip(next))} |`);
    }
  }
  const file = join(dev, "README.md");
  if (!existsSync(file)) throw new Error(`${file} is missing`);
  const readme = readFileSync(file, "utf8");
  const a = readme.indexOf(BEGIN);
  const b = readme.indexOf(END);
  if (a < 0 || b < a) throw new Error(`${file}: the track table markers are missing`);
  const table = [BEGIN, "", "| Track | State | Owner | Next action |", "|---|---|---|---|", ...rows, "", END].join("\n");
  const next = readme.slice(0, a) + table + readme.slice(b + END.length);
  return { tracks: rows.length, problems, readme: next, stale: next !== readme };
}

export interface DevResult { ok: boolean; lines: string[] }

/** `hub dev index`: rewrites the table of one folder; with `check` writes nothing and fails on drift. `fix` is the command named in the stale message. */
export function indexDev(dev: string, check: boolean, fix: string): DevResult {
  let k: Kanban;
  try { k = readKanban(dev); } catch (e) { return { ok: false, lines: [(e as Error).message] }; }
  if (check) {
    const problems = [...k.problems, ...(k.stale ? [`README.md track table is stale: run \`${fix}\``] : [])];
    return problems.length
      ? { ok: false, lines: problems }
      : { ok: true, lines: [`ok: ${k.tracks} tracks, README table matches the directories`] };
  }
  if (k.stale) writeFileSync(join(dev, "README.md"), k.readme);
  return { ok: true, lines: [...k.problems.map((p) => `warning: ${p}`), `wrote ${k.tracks} rows`] };
}

/** Every file under `root` as relative paths. */
function filesUnder(root: string, rel = ""): string[] {
  const out: string[] = [];
  for (const e of readdirSync(join(root, rel), { withFileTypes: true })) {
    const r = join(rel, e.name);
    if (e.isDirectory()) out.push(...filesUnder(root, r));
    else out.push(r);
  }
  return out.sort();
}

export const devFolder = (projectFolder: string): string => join(projectFolder, DEV_DIR);

/** The files `hub dev init` writes (paths relative to the `@dev` folder). The test pins this list. */
export const devTemplateFiles = (coreRoot: string = CORE_ROOT): string[] => filesUnder(join(coreRoot, DEV_TEMPLATE));

/**
 * `hub dev init <slug>`: the `@dev` skeleton in a project folder, copied from the core's template. Dry run unless `apply`. A file that already
 * exists is left as it is (never overwritten), so a second run changes nothing.
 */
export function initDev(slug: string, projectFolder: string, apply: boolean, coreRoot: string = CORE_ROOT): DevResult {
  if (!existsSync(join(projectFolder, "project.md"))) return { ok: false, lines: [`no ${join(projectFolder, "project.md")}: the project must exist first (project-setup)`] };
  const src = join(coreRoot, DEV_TEMPLATE);
  if (!existsSync(src)) return { ok: false, lines: [`the core at ${coreRoot} has no ${DEV_TEMPLATE}: update the core first`] };
  const dst = devFolder(projectFolder);
  const lines: string[] = [];
  let made = 0;
  for (const f of filesUnder(src)) {
    const to = join(dst, f);
    const shown = join(DEV_DIR, f);
    if (existsSync(to)) { lines.push(`exists   ${shown}`); continue; }
    made++;
    lines.push(`${apply ? "created " : "would create"} ${shown}`);
    if (!apply) continue;
    mkdirSync(dirname(to), { recursive: true });
    writeFileSync(to, readFileSync(join(src, f), "utf8").replace(/\{\{SLUG\}\}/g, slug));
  }
  lines.push(apply ? `${slug}: ${made} file(s) created in ${relative(dirname(projectFolder), dst)}` : `dry run, nothing written: add --apply to create ${made} file(s)`);
  return { ok: true, lines };
}

export type DevLevel = "pass" | "warn" | "fail";

/** The doctor's view of one project: WARN when there is no folder, FAIL on a stale README or a contradicting plan. */
export function checkDev(slug: string, projectFolder: string): { level: DevLevel; detail: string } {
  const dev = devFolder(projectFolder);
  if (!existsSync(dev) || !statSync(dev).isDirectory()) return { level: "warn", detail: `${slug}: no ${DEV_DIR}/ (run \`hub dev init ${slug} --apply\`)` };
  const r = indexDev(dev, true, `hub dev index ${slug}`);
  return r.ok ? { level: "pass", detail: `${slug}: ${r.lines[0]}` } : { level: "fail", detail: `${slug}: ${r.lines.join("; ")}` };
}
