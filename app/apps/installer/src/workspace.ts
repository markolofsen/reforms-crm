import { existsSync, readFileSync, writeFileSync } from "node:fs";
import path from "node:path";
import type { Ctx } from "./context";

/**
 * `hub workspace init|check` (decision 0018). An instance may carry its own apps and packages (`apps/*`, `packages/*`); they join the core's
 * packages in ONE pnpm/turbo workspace rooted at the instance. The three root files are GENERATED from `core/app` (versions, turbo tasks, pnpm
 * policy), never hand-written, so the core's own `app/` workspace stays untouched.
 */
export interface WorkspaceResult { ok: boolean; lines: string[] }

const MARK = "hub-generated: `hub workspace init` (decision 0018). Do not edit; change the core templates or run it again.";
const FILES = ["package.json", "pnpm-workspace.yaml", "turbo.json"] as const;
type FileName = (typeof FILES)[number];

const coreApp = (ctx: Ctx): string => path.join(ctx.paths.home, "core", "app");
const read = (f: string): string => readFileSync(f, "utf8");

/** What the three files must contain, derived from the core in `<home>/core/app`. Undefined detail = cannot generate. */
export function wanted(ctx: Ctx): { files: Record<FileName, string>; error?: string } {
  const empty = { "package.json": "", "pnpm-workspace.yaml": "", "turbo.json": "" } as Record<FileName, string>;
  const app = coreApp(ctx);
  const pkgFile = path.join(app, "package.json"), wsFile = path.join(app, "pnpm-workspace.yaml"), turboFile = path.join(app, "turbo.json");
  for (const f of [pkgFile, wsFile, turboFile]) if (!existsSync(f)) return { files: empty, error: `${f} is missing: core/ is not checked out (run \`hub core install\`)` };
  const core = JSON.parse(read(pkgFile)) as { packageManager?: string; engines?: unknown; devDependencies?: Record<string, string> };
  const dev: Record<string, string> = {};
  for (const k of ["turbo", "typescript"]) if (core.devDependencies?.[k]) dev[k] = core.devDependencies[k];
  const pkg = {
    name: `${path.basename(ctx.paths.home)}-workspace`,
    private: true,
    "//": MARK,
    packageManager: core.packageManager,
    engines: core.engines,
    scripts: { build: "turbo run build", typecheck: "turbo run typecheck", test: "turbo run test" },
    devDependencies: dev,
  };
  // The core's policy lines (everything but its own `packages:` block) are copied as they are.
  const policy = read(wsFile).split("\n").filter((l, i, all) => {
    if (/^packages:/.test(l)) return false;
    if (/^\s+- (apps|packages)\/\*\s*$/.test(l) && all.slice(0, i).some((x) => /^packages:/.test(x))) return false;
    return true;
  }).join("\n").replace(/^\n+/, "");
  // The catalog (`catalog:` versions, P45 C5) is part of the policy: without it every core package's `"catalog:"` fails `pnpm install` at the instance root.
  if (/^catalog:/m.test(read(wsFile)) && !/^catalog:/m.test(policy)) return { files: empty, error: `${wsFile}: the catalog block could not be copied` };
  const yaml = `# ${MARK}\npackages:\n  - core/app/apps/*\n  - core/app/packages/*\n  - apps/*\n  - packages/*\n${policy.endsWith("\n") ? policy : `${policy}\n`}`;
  // `$TURBO_ROOT$` is the instance root here: a core input path (`$TURBO_ROOT$/packages/ui/**`) lives under core/app.
  const turbo = `${JSON.stringify({ "//": MARK, ...(JSON.parse(read(turboFile).replaceAll("$TURBO_ROOT$/", "$TURBO_ROOT$/core/app/")) as object) }, null, 2)}\n`;
  return { files: { "package.json": `${JSON.stringify(pkg, null, 2)}\n`, "pnpm-workspace.yaml": yaml, "turbo.json": turbo } };
}

const generated = (text: string): boolean => text.includes("hub-generated:");

/** `hub workspace init`: write the three files. Never overwrites a file that is not ours. Dry run unless apply. */
export function workspaceInit(ctx: Ctx, apply: boolean): WorkspaceResult {
  const w = wanted(ctx);
  if (w.error) return { ok: false, lines: [w.error] };
  const out: string[] = [];
  for (const f of FILES) {
    const file = path.join(ctx.paths.home, f);
    if (existsSync(file) && !generated(read(file))) return { ok: false, lines: [...out, `${f} exists and was not generated by \`hub workspace init\`: move it away first`] };
    const same = existsSync(file) && read(file) === w.files[f];
    out.push(`${same ? "unchanged" : apply ? "wrote" : "would write"} ${f}`);
    if (apply && !same) writeFileSync(file, w.files[f]);
  }
  if (!apply) out.push("dry run: nothing changed. Add --apply, then `pnpm install` at the instance root.");
  return { ok: true, lines: out };
}

/** `hub workspace check`: the three files exist and equal what the current core generates (catches version drift after `hub core update`). */
export function workspaceCheck(ctx: Ctx): WorkspaceResult {
  const w = wanted(ctx);
  if (w.error) return { ok: false, lines: [w.error] };
  const bad = FILES.filter((f) => { const file = path.join(ctx.paths.home, f); return !existsSync(file) || read(file) !== w.files[f]; });
  return bad.length ? { ok: false, lines: [`out of date or missing: ${bad.join(", ")}; run \`hub workspace init --apply\``] } : { ok: true, lines: ["workspace files match the core"] };
}
