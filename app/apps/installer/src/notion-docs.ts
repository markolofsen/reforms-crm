import { readdirSync, readFileSync } from "node:fs";
import path from "node:path";

/** Where the knowledge pack lives inside the core. */
export const NOTION_PACK = "app/projects/_template/notion-crm";

interface Prop {
  type: string; writer?: string; options?: string[]; target?: string; reverse?: string; limit?: number; via?: string; formula?: string;
  trap?: number; skip?: string; note?: string; flag?: string; optional?: boolean; vertical?: boolean; ads?: boolean; createAs?: string;
}
interface Schema { database: string; title: string; properties: Record<string, Prop> }

const cell = (s: string) => s.replace(/\|/g, "\\|").replace(/\s*\n\s*/g, " ").trim();

function flags(p: Prop): string {
  const f: string[] = [];
  if (p.vertical) f.push("vertical");
  if (p.ads) f.push("ads");
  if (p.optional) f.push("optional");
  if (p.trap) f.push(`skipped (trap ${p.trap})`);
  if (p.skip) f.push(`skip: ${p.skip}`);
  if (p.flag) f.push(p.flag);
  return f.join(", ");
}

function typeOf(p: Prop): string {
  if (p.type === "relation") return `relation to ${p.target ?? "?"}${p.limit === 1 ? " (one)" : ""}${p.reverse ? `, reverse "${p.reverse}"` : ""}`;
  if (p.type === "rollup" || p.type === "formula") return p.type + (p.via ? ` via ${p.via}` : "");
  return p.type + (p.createAs ? ` (created as ${p.createAs})` : "");
}

/** @docs/notion/fields.md, generated from the pack's schema/*.json: a reader never has to open the JSON. */
export function renderNotionFields(root: string): string {
  const dir = path.join(root, ...NOTION_PACK.split("/"), "schema");
  const dbs = readdirSync(dir).filter((f) => f.endsWith(".json")).sort().map((f) => JSON.parse(readFileSync(path.join(dir, f), "utf8")) as Schema);
  const out: string[] = [
    "# Notion fields, per database",
    "",
    `<!-- Generated by \`pnpm hub docs\` from ${NOTION_PACK}/schema/*.json. Do not edit; change the schema file instead. -->`,
    "",
    "Every property of every database the Notion CRM deploys, with its type, who writes it and the select options. Names are exactly as Notion shows them: Hub and the CRM sync look fields up by name, so never rename one. The meaning and the rules behind a module are in the pack's markdown (`02` to `07`); how to set Notion up is in [`README.md`](README.md).",
    "",
    "**Writer** says who may change the field: `Hub` (the local app), `CRM` or `sync` (the Django CRM), `people` (a person by hand), `agent` (a workflow, after the owner's OK). One owner per field.",
    "",
    "## Databases",
    "",
    ...dbs.map((d) => `- [${d.title}](#${d.title.toLowerCase().replace(/[^a-z0-9 -]/g, "").replace(/ /g, "-")}) (\`${d.database}\`, ${Object.keys(d.properties).length} fields)`),
    "",
  ];
  for (const d of dbs) {
    out.push(`## ${d.title}`, "", `Pack file: \`schema/${d.database}.json\`.`, "", "| Field | Type | Writer | Options and notes |", "|---|---|---|---|");
    for (const [name, p] of Object.entries(d.properties)) {
      const bits = [p.options?.length ? `Options: ${p.options.join(", ")}.` : "", p.formula ? `Formula: ${p.formula}.` : "", p.note ?? "", flags(p) ? `Flags: ${flags(p)}.` : ""].filter(Boolean).join(" ");
      out.push(`| ${cell(name)} | ${cell(typeOf(p))} | ${cell(p.writer ?? "")} | ${cell(bits)} |`);
    }
    out.push("");
  }
  return out.join("\n");
}
