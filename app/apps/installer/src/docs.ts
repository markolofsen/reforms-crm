import type { Step } from "./types.ts";

/** The line every page that lists checks ends with (the architecture-change rule, CLAUDE.md). */
export const UPDATE_LINE = "Update this page when the architecture changes.";

const FLAG: Record<NonNullable<Step["optional"]>, string> = { automation: "optional extra, `--automation`" };

/**
 * @docs/setup/checklist.md: the working-order checklist of every node (tools, files, mail, Notion, server, backups), generated from
 * the step list, so a check that is added, renamed or removed changes this page in the same change. Order = the order doctor runs.
 */
export function renderChecklist(steps: Step[]): string {
  const out: string[] = [
    "# Setup checklist",
    "",
    "<!-- Generated by `pnpm hub docs` from app/apps/installer/src/steps. Do not edit; change the step instead. -->",
    "",
    "Work top to bottom. `hub doctor` runs every box below that is not an optional extra and prints PASS, WARN or FAIL per step id; `hub doctor --automation` adds the extras. A FAIL names its own fix. `hub guide` prints the by-hand steps. Which access goes to what: `@docs/setup/access.md`.",
    "",
  ];
  let group = "";
  for (const s of steps) {
    if (s.group !== group) { group = s.group; out.push(`## ${group}`, ""); }
    const flag = s.optional ? FLAG[s.optional] : s.audit ? "`hub doctor` only; setup and install never run it" : "";
    out.push(`- [ ] **${s.title}** (\`${s.id}\`${flag ? `; ${flag}` : ""})`, `  - Proves: ${s.verifies}`);
    if (s.manual) out.push(`  - You: ${s.manual.steps.join(" ")}`);
    else if (s.does) out.push(`  - \`hub install\` fixes it: ${s.does}`);
  }
  out.push("", UPDATE_LINE);
  return out.join("\n") + "\n";
}
